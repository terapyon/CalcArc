/**
 * 表示文字列を数に戻す。
 *
 * **許容誤差はここに書かない。** corpus の JSON が持つ(CLAUDE.md の規約)。
 * ここがするのは書式の逆変換だけである。
 *
 * **電卓が実際に出す書式だけを受け付ける。** 以前はここが `Number()` に
 * 丸投げしていて、`Number()` が親切に解してしまうものを黙って通していた。
 * 敵対者レビュー(2026-08-15)の実測: `""` → 0、`" "` → 0、`"\n"` → 0、
 * `"0x10"` → 16、`"0b101"` → 5、`"+5"` → 5。とくに**空文字列が 0 になること**
 * は、「あらゆるキー列に定数を返すだけの偽ハーネス」に同値ケース 2000 件が
 * 全件通る経路の一部だった。表示が空でも数になるなら、表示が壊れたことを
 * この層は検出できない。
 *
 * 受け付けるのは「先頭の負号(ASCII の `-`)+ 十進の整数部 + 省略可能な
 * 小数部 + 省略可能な小文字 `e` の指数部」だけである。前後の空白も、`+` の
 * 符号も、基数接頭辞も、`Infinity` も `NaN` も通さない。
 *
 * **観測した書式だけを解する。** 桁区切りのカンマと U+2212(数学用マイナス)
 * を吸収する変換をブリーフの当初案は持っていたが、9 探り
 * (docs/corpus-measurements.md)のどれも出さなかったため、レビュー修正
 * ラウンド 1 で落とした。負号は ASCII の "-" のみを観測している。
 * カンマや U+2212 が実際に観測されたら、そのときに実測付きで足す。
 *
 * **そのときが来た(2026-08-16、main 取り込み)。** `format_real` が整数部を
 * 3 桁ごとに区切るようになり(`numeric/format.rs` の `group_integer_part`)、
 * 値ケース 4000 件のうち 1498 件がカンマを持つようになった。実測:
 * `9 9 9 9 9 9 9 9 9 9 eq` → `"9,999,999,999"`。**落としてあったので
 * 1498 件が赤くなり、実測付きで足し直せた**——投機的に持っていたら、
 * この変化は無検証のまま通っていた。
 *
 * **カンマは単純に除去しない。** `"1,2,3"` を 123 として通すと、
 * **区切り位置のバグをこの層が捕まえられなくなる**。区切りは整数部だけで、
 * 3 桁ごと、最上位の群は 1〜3 桁——この形に合うことを検証してから外す。
 * 小数部と指数部にカンマは入らない(実測: `1,234.5678`、`1e10`)。
 *
 * 指数部は段階 2 のコーパスでは一度も観測されていない(生成は |値| が
 * 1e-6 〜 1e9 に収まる範囲だけ)。それでも書式として許しているのは、
 * 段階 3 で指数表記が入ったときにここが**書式の問題**として落ちるより、
 * 素直に読めた方がよいためである。読めた値が正しいかは呼び出し側が見る。
 *
 * 複素数の表示(例: "j2")もここでは扱わない。実数の書式ではないので下の
 * 正規表現で弾かれる。実数以外を生成しうるキー列をコーパスが含める場合は、
 * 呼び出し側が parseDisplay に渡す前に実数か複素数かを別途判定する必要がある。
 *
 * **由来の訂正(2026-08-16、main 取り込み)。** ここには以前「実測では
 * sqrt(-4) が "j2" を返した」と書いてあったが、main で負数の平方根は
 * `Math ERROR` / `DomainError` になった(実測)。**"j2" という表示自体は
 * 今も出る**——`j` `2` と打てばよい——ので、嘘になったのは文字列ではなく
 * **その由来**である。数でない表示を弾くという契約は変わっていない。
 */
/**
 * 整数部は「区切り無しの数字列」か「3 桁ごとにカンマで区切られた数字列」の
 * どちらか。後者は最上位の群が 1〜3 桁で、以降はちょうど 3 桁ずつである。
 * `1,23,456` や `,123` や `1,2345` はここで落ちる。
 */
const REAL_DISPLAY = /^-?(?:\d+|\d{1,3}(?:,\d{3})+)(?:\.\d+)?(?:e[+-]?\d+)?$/;

export function parseDisplay(main: string): number {
  if (typeof main !== "string" || !REAL_DISPLAY.test(main)) {
    // 黙って 0 や NaN を返すと、比較が「誤差の範囲外」ではなく「常に一致」
    // または「常に不一致」に化けて、原因が書式なのか計算なのか分からなくなる。
    throw new Error(
      `display: ${JSON.stringify(main)} is not a real number in the format ` +
        "this calculator displays (optional '-', decimal digits grouped in " +
        "threes or not at all, optional fraction, optional lowercase 'e' " +
        "exponent)",
    );
  }
  // 書式を検証してから外す。`Number("1,234")` は NaN なので、外さないと
  // 下の有限判定で落ちる——が、そこで落とすと原因が「区切り位置が不正」
  // なのか「値が f64 に収まらない」なのか区別できなくなる。
  const value = Number(main.replace(/,/g, ""));
  if (!Number.isFinite(value)) {
    // 書式は通ったが数として有限でない——桁数が f64 の範囲を超えた場合など。
    throw new Error(`display: cannot read ${JSON.stringify(main)} as a number`);
  }
  return value;
}
