/**
 * **計算しないパネルで、押せない演算子キー**（ユーザー裁定 2026-08-26）。
 *
 * LLM・Data Scale・Transfer の 3 つは、打った文字列をそのまま
 * `expr.integer(...)` に渡す。式を組み立てる入口が無いので、`( ) ÷ × − + =`
 * を押しても**何も起きなかった**——3 パネル × 7 個 = 21 個。
 *
 * **裁定は「盤面はそのまま、無効化する」である。** 枠も位置もラベルも
 * 動かさない。外して詰めると盤面が電卓に見えなくなり、空きスロットに
 * 置き換えると 25 マス中 9〜12 マスが空き、読み上げも「空き」を同じ数だけ
 * 拾う。**どちらも見た目と読み上げを悪くする**ので、そうしないことを選んだ。
 *
 * ## 淡色の意味が 2 つになる
 *
 * `Key.module.css` の `:disabled` は今日まで「**いまは押せない**」だけを
 * 意味していた——`del` は数字面以外で、`unit:b`/`unit:m` は桁が足りないとき。
 * どれも**状態が変われば押せるようになる**。
 *
 * **ここで足す 7 個は「このパネルには存在しない機能」で、何をしても
 * 押せるようにならない。** 同じ淡色が「待てば押せる」と「永久に押せない」の
 * 2 つを指すことになる。
 *
 * **これは承知のうえの選択である**（2026-08-26 のユーザー裁定）。弱点も
 * 挙がっていた——**利用者が何度も試すかもしれない**。それでも、盤面の見た目を
 * 保つほうを採った。**淡色を 2 つの意味に分けるなら、それは盤面の作り直しと
 * 一緒にやる話**であって、この 7 個だけのために新しい見た目を作らない。
 *
 * だから条件は付けない。`keyDisabled` の他の枝と違い、**常に押せない**。
 */
const DEAD_OPERATOR_TOKENS: readonly string[] = [
  "lparen",
  "rparen",
  "div",
  "mul",
  "sub",
  "add",
  "eq",
];

/**
 * このトークンが「計算しないパネルでは押せない演算子」か。
 *
 * **3 パネルで同じ綴りを書き写さないために、ここに 1 つ置く**（`FIELD_ORDER`
 * が 2 か所にある問題を、もう 1 組は作らない）。**綴りそのものは
 * `KEY_TOKENS` と共有している**——Scientific・Finance・Convert は同じ綴りで
 * 実際に式を組むので、そちらは変えない。ここが決めるのは
 * 「この 3 パネルでは押せない」ことだけである。
 */
export function isDeadOperator(token: string): boolean {
  return DEAD_OPERATOR_TOKENS.includes(token);
}
